# 1.Print all prime numbers between input range (Ex – input 20 50, prints all prime numbers between 20 and 50).

print("Prime numbers between 20 and 50:")

for num in range(20, 51):
    if num > 1:
        for i in range(2, int(num**0.5) + 1):
            if num % i == 0:
                break
        else:
            print(num, end=" ")

